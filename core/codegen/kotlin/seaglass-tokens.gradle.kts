/*
 * Sea Glass token sync
 * - Source of truth: tokens.json, exported from the Sea Glass v1 design system.
 * - Optional palettes.json beside it adds the full HCT tone sets and hue/chroma; tones in tokens.json win.
 * - generateSeaGlassTokens writes Kotlin into <namespace>.tokens; verifySeaGlassTokens fails preBuild and check when it drifts.
 * - Overrides in gradle.properties: seaglass.tokens.dir (relative to the root project, default <module>/design-tokens),
 *   seaglass.tokens.package, seaglass.tokens.srcDir.
 */

val seaGlassTokensPackage: String = providers.gradleProperty("seaglass.tokens.package").orNull
    ?: extensions.findByName("android")
        ?.let { ext -> runCatching { ext.javaClass.getMethod("getNamespace").invoke(ext) as String? }.getOrNull() }
        ?.let { "$it.tokens" }
    ?: "dev.seaglass.tokens"
val seaGlassTokensSrcDir: String = providers.gradleProperty("seaglass.tokens.srcDir").orNull ?: "src/main/kotlin"
val seaGlassTokensDir: File = providers.gradleProperty("seaglass.tokens.dir").orNull
    ?.let { rootDir.resolve(it).canonicalFile }
    ?: layout.projectDirectory.dir("design-tokens").asFile
val seaGlassTokensJson: File = seaGlassTokensDir.resolve("tokens.json")
val seaGlassPalettesJson: File = seaGlassTokensDir.resolve("palettes.json")
val seaGlassTokensOut = layout.projectDirectory.dir("$seaGlassTokensSrcDir/${seaGlassTokensPackage.replace('.', '/')}")
val seaGlassTokensFix = "./gradlew ${if (project.path == ":") "" else project.path}:generateSeaGlassTokens"

@UntrackedTask(because = "Writes generated Kotlin into the source tree")
abstract class GenerateSeaGlassTokens : DefaultTask() {
    @get:InputFile abstract val tokensFile: RegularFileProperty
    @get:Optional @get:InputFile abstract val palettesFile: RegularFileProperty
    @get:Input abstract val packageName: Property<String>
    @get:Internal abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val files = SeaGlassCodegen.render(tokensFile.get().asFile.readText(), palettesFile.orNull?.asFile?.readText(), packageName.get())
        val dir = outputDir.get().asFile.apply { mkdirs() }
        val stale = SeaGlassCodegen.generatedFiles(dir).filter { it.name !in files.keys }
        stale.forEach { it.delete() }
        files.forEach { (name, text) -> File(dir, name).writeText(text) }
        logger.lifecycle("Sea Glass tokens: wrote ${files.size} files to $dir" + if (stale.isEmpty()) "" else ", removed ${stale.joinToString { it.name }}")
    }
}

@UntrackedTask(because = "Compares generated Kotlin in the source tree")
abstract class VerifySeaGlassTokens : DefaultTask() {
    @get:InputFile abstract val tokensFile: RegularFileProperty
    @get:Optional @get:InputFile abstract val palettesFile: RegularFileProperty
    @get:Input abstract val packageName: Property<String>
    @get:Internal abstract val generatedDir: DirectoryProperty
    @get:Internal abstract val fixCommand: Property<String>

    @TaskAction
    fun verify() {
        val expected = SeaGlassCodegen.render(tokensFile.get().asFile.readText(), palettesFile.orNull?.asFile?.readText(), packageName.get())
        val dir = generatedDir.get().asFile
        val problems = mutableListOf<String>()
        expected.forEach { (name, text) ->
            val file = File(dir, name)
            when {
                !file.exists() -> problems += "missing   $name"
                SeaGlassCodegen.normalize(file.readText()) != text -> problems += "outdated  $name"
            }
        }
        SeaGlassCodegen.generatedFiles(dir).filter { it.name !in expected.keys }.forEach { problems += "stale     ${it.name}" }
        if (problems.isNotEmpty()) {
            throw GradleException(
                "Sea Glass tokens are out of sync with ${tokensFile.get().asFile.path}:\n  " +
                    problems.joinToString("\n  ") + "\nRun ${fixCommand.get()} and commit the result."
            )
        }
    }
}

object SeaGlassCodegen {
    const val MARKER: String = "// Generated by seaglass-tokens.gradle.kts"

    private val SCHEME_ROLES = setOf(
        "primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "inversePrimary",
        "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
        "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
        "background", "onBackground", "surface", "onSurface", "surfaceVariant", "onSurfaceVariant",
        "surfaceTint", "inverseSurface", "inverseOnSurface",
        "error", "onError", "errorContainer", "onErrorContainer",
        "outline", "outlineVariant", "scrim", "surfaceBright", "surfaceDim",
        "surfaceContainer", "surfaceContainerHigh", "surfaceContainerHighest", "surfaceContainerLow", "surfaceContainerLowest",
    )
    private val BASELINE_TYPE = listOf(
        "displayLarge", "displayMedium", "displaySmall", "headlineLarge", "headlineMedium", "headlineSmall",
        "titleLarge", "titleMedium", "titleSmall", "bodyLarge", "bodyMedium", "bodySmall",
        "labelLarge", "labelMedium", "labelSmall",
    )
    private val PALETTE_NAMES = mapOf("seapink" to "SeaPink", "neutralvariant" to "NeutralVariant")
    private val NON_DIMEN_FAMILIES = setOf("name", "version", "meta", "color", "type", "shadow", "shape")
    private val KEYWORDS = setOf(
        "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is",
        "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof", "val", "var", "when", "while",
    )
    private val PALETTE_TONE = Regex("""^([a-z]+(?:-[a-z]+)*)-(\d{1,3})$""")
    private val LENGTH = Regex("""^(-?\d*\.?\d+)(px|rem|em|%)?$""")

    fun normalize(text: String): String = text.replace("\r\n", "\n")

    fun generatedFiles(dir: File): List<File> =
        dir.listFiles()?.filter { f -> f.isFile && f.extension == "kt" && f.useLines { it.firstOrNull()?.startsWith(MARKER) == true } }.orEmpty()

    /*
     * - Parses tokens.json (and palettes.json) into the token families
     * - Returns file name -> Kotlin source for palettes, colour schemes, type, dimens, shapes, shadows and token info
     */
    fun render(tokensText: String, palettesText: String?, pkg: String): Map<String, String> {
        val tokensSource = normalize(tokensText)
        val root = obj(JsonSlurper().parseText(tokensSource))
        val palettes = palettesText?.let { obj(JsonSlurper().parseText(normalize(it))) }.orEmpty()
        val out = linkedMapOf<String, String>()
        val color = obj(root["color"])
        val themes = list(color["themes"]).map { obj(it)["id"].toString() }.ifEmpty { listOf("light", "dark") }
        val colors = list(color["tokens"]).map { obj(it) }

        val values = colors.associate { t -> t["name"].toString() to themes.associateWith { th -> pick(t["value"], th, themes.first()) } }
        fun resolve(name: String, theme: String, depth: Int = 0): String {
            val v = values[name]?.get(theme) ?: error("Unknown colour token '$name'")
            if (!v.startsWith("{")) return v
            require(depth < 16) { "Alias chain too deep at '$name'" }
            return resolve(v.trim('{', '}'), theme, depth + 1)
        }
        val argbs = values.keys.associateWith { n -> themes.associateWith { th -> argb(resolve(n, th)) } }

        val paletteKeys = palettes.keys.associateBy { key(it) }
        val toneGroups = linkedMapOf<String, LinkedHashMap<Int, Long>>()
        val toneTokens = mutableSetOf<String>()
        colors.forEach { t ->
            val name = t["name"].toString()
            val m = PALETTE_TONE.matchEntire(name) ?: return@forEach
            val tone = m.groupValues[2].toInt()
            val perTheme = argbs.getValue(name).values.toSet()
            if (tone <= 100 && perTheme.size == 1) toneGroups.getOrPut(key(m.groupValues[1])) { linkedMapOf() }[tone] = perTheme.first()
        }
        toneGroups.keys.retainAll { it in paletteKeys || toneGroups.getValue(it).size >= 3 }
        colors.forEach { t ->
            val m = PALETTE_TONE.matchEntire(t["name"].toString())
            if (m != null && key(m.groupValues[1]) in toneGroups) toneTokens += t["name"].toString()
        }
        out["SeaGlassPalettes.kt"] = palettesFile(pkg, toneGroups, palettes, paletteKeys)

        val schemeTokens = colors.map { it["name"].toString() }.filter { it !in toneTokens && camel(it) in SCHEME_ROLES }
        val extended = colors.map { it["name"].toString() }.filter { it !in toneTokens && it !in schemeTokens }
        out["SeaGlassColorSchemes.kt"] = schemesFile(pkg, themes, schemeTokens, extended, argbs)

        val type = obj(root["type"])
        if (list(type["groups"]).isNotEmpty()) out["SeaGlassTypeScale.kt"] = typeFile(pkg, list(type["groups"]).map { obj(it) })

        val dimenFamilies = root.filterKeys { it !in NON_DIMEN_FAMILIES }.mapValues { list(obj(it.value)["tokens"]).map { t -> obj(t) } }.filterValues { it.isNotEmpty() }
        if (dimenFamilies.isNotEmpty()) out["SeaGlassDimens.kt"] = dimensFile(pkg, dimenFamilies)

        val shapes = list(obj(root["shape"])["tokens"]).map { obj(it) }
        if (shapes.isNotEmpty()) out["SeaGlassShapeTokens.kt"] = shapesFile(pkg, shapes)

        val shadows = list(obj(root["shadow"])["tokens"]).map { obj(it) }
        if (shadows.isNotEmpty()) out["SeaGlassShadowTokens.kt"] = shadowsFile(pkg, themes, shadows)

        out["SeaGlassTokenInfo.kt"] = infoFile(pkg, root, tokensSource)
        return out
    }

    private fun palettesFile(pkg: String, groups: Map<String, Map<Int, Long>>, palettes: Map<String, Any?>, paletteKeys: Map<String, String>): String {
        val order = groups.keys + paletteKeys.keys.filter { it !in groups }
        val body = StringBuilder()
        order.forEach { k ->
            val hct = paletteKeys[k]?.let { obj(palettes[it]) }.orEmpty()
            val tones = sortedMapOf<Int, Long>()
            obj(hct["tones"]).forEach { (t, hex) -> tones[t.toInt()] = argb(hex.toString()) }
            groups[k]?.let { tones.putAll(it) }
            body.append("    public val ${paletteName(k)}: TonalTones = TonalTones(\n")
            body.append("        hue = ${float(hct["hue"])},\n        chroma = ${float(hct["chroma"])},\n        tones = mapOf(\n")
            tones.forEach { (t, c) -> body.append("            $t to ${kColor(c)},\n") }
            body.append("        ),\n    )\n")
        }
        body.append("\n    public val byKey: Map<String, TonalTones> = mapOf(\n")
        order.forEach { k -> body.append("        \"${paletteKeys[k] ?: k}\" to ${paletteName(k)},\n") }
        body.append("    )\n")
        return file(pkg, listOf("androidx.compose.runtime.Immutable", "androidx.compose.ui.graphics.Color"), """
            |@Immutable
            |public class TonalTones(
            |    public val hue: Float,
            |    public val chroma: Float,
            |    private val tones: Map<Int, Color>,
            |) {
            |    public val available: Set<Int> get() = tones.keys
            |
            |    public operator fun get(tone: Int): Color = tones[tone] ?: error("Tone ${'$'}tone is not in the generated set")
            |}
            |
            |public object SeaGlassPalettes {
            |
        """.trimMargin() + body + "}\n")
    }

    private fun schemesFile(pkg: String, themes: List<String>, scheme: List<String>, extended: List<String>, argbs: Map<String, Map<String, Long>>): String {
        val sb = StringBuilder()
        val imports = sortedSetOf("androidx.compose.ui.graphics.Color")
        if (scheme.isNotEmpty()) {
            imports += "androidx.compose.material3.ColorScheme"
            themes.forEach { th ->
                val builder = if ("dark" in th.lowercase()) "darkColorScheme" else "lightColorScheme"
                imports += "androidx.compose.material3.$builder"
                sb.append("public val SeaGlass${pascal(th)}Scheme: ColorScheme = $builder(\n")
                scheme.forEach { n -> sb.append("    ${camel(n)} = ${kColor(argbs.getValue(n).getValue(th))},\n") }
                sb.append(")\n\n")
            }
        }
        if (extended.isNotEmpty()) {
            imports += "androidx.compose.runtime.Immutable"
            sb.append("@Immutable\npublic data class SeaGlassExtendedColors(\n")
            extended.forEach { n -> sb.append("    public val ${ident(camel(n))}: Color,\n") }
            sb.append(")\n")
            themes.forEach { th ->
                sb.append("\npublic val SeaGlass${pascal(th)}ExtendedColors: SeaGlassExtendedColors = SeaGlassExtendedColors(\n")
                extended.forEach { n -> sb.append("    ${ident(camel(n))} = ${kColor(argbs.getValue(n).getValue(th))},\n") }
                sb.append(")\n")
            }
        }
        return file(pkg, imports.toList(), sb.toString().trimEnd() + "\n")
    }

    private fun typeFile(pkg: String, groups: List<Map<String, Any?>>): String {
        val styles = groups.flatMap { g -> list(g["styles"]).map { obj(it) } }
        val sb = StringBuilder("public class SeaGlassTextStyles(fontFamily: FontFamily) {\n")
        var usesEm = false
        styles.forEach { s ->
            val args = mutableListOf("fontFamily = fontFamily")
            s["fontWeight"]?.let { args += "fontWeight = FontWeight(${weight(it)})" }
            s["fontSize"]?.let { args += "fontSize = ${textUnit(it)}" }
            s["lineHeight"]?.let { args += "lineHeight = ${textUnit(it)}" }
            s["letterSpacing"]?.let { args += "letterSpacing = ${textUnit(it)}" }
            if (args.any { it.endsWith(".em") }) usesEm = true
            sb.append("    public val ${ident(camel(s["name"].toString()))}: TextStyle = TextStyle(\n")
            args.forEach { sb.append("        $it,\n") }
            sb.append("    )\n")
        }
        sb.append("}\n")
        val names = styles.map { camel(it["name"].toString()) }.toSet()
        val baseline = BASELINE_TYPE.filter { it in names }
        val imports = mutableListOf("androidx.compose.ui.text.TextStyle", "androidx.compose.ui.text.font.FontFamily", "androidx.compose.ui.text.font.FontWeight", "androidx.compose.ui.unit.sp")
        if (usesEm) imports += "androidx.compose.ui.unit.em"
        if (baseline.isNotEmpty()) {
            imports += "androidx.compose.material3.Typography"
            sb.append("\npublic fun SeaGlassTextStyles.toTypography(): Typography = Typography(\n")
            baseline.forEach { sb.append("    $it = $it,\n") }
            sb.append(")\n")
        }
        return file(pkg, imports.sorted(), sb.toString())
    }

    private fun dimensFile(pkg: String, families: Map<String, List<Map<String, Any?>>>): String {
        val sb = StringBuilder()
        var usesDp = false
        families.forEach { (family, tokens) ->
            sb.append("public object SeaGlass${pascal(family)}Tokens {\n")
            propertyNames(tokens.map { it["name"].toString() }).forEach { (name, prop) ->
                val (type, expr) = dimen(tokens.first { it["name"].toString() == name }["value"])
                if (type == "Dp") usesDp = true
                sb.append("    public val $prop: $type = $expr\n")
            }
            sb.append("}\n\n")
        }
        val imports = if (usesDp) listOf("androidx.compose.ui.unit.Dp", "androidx.compose.ui.unit.dp") else emptyList()
        return file(pkg, imports, sb.toString().trimEnd() + "\n")
    }

    private fun shapesFile(pkg: String, tokens: List<Map<String, Any?>>): String {
        val sb = StringBuilder("""
            |@Immutable
            |public data class SeaGlassCornerSpec(
            |    public val topLeftX: Float,
            |    public val topRightX: Float,
            |    public val bottomRightX: Float,
            |    public val bottomLeftX: Float,
            |    public val topLeftY: Float,
            |    public val topRightY: Float,
            |    public val bottomRightY: Float,
            |    public val bottomLeftY: Float,
            |)
            |
            |public object SeaGlassShapeTokens {
            |
        """.trimMargin())
        propertyNames(tokens.map { it["name"].toString() }).forEach { (name, prop) ->
            val raw = tokens.first { it["name"].toString() == name }["value"].toString()
            val corners = corners(raw)
            if (corners != null) sb.append("    public val $prop: SeaGlassCornerSpec = SeaGlassCornerSpec(${corners.joinToString { float(it) }})\n")
            else sb.append("    public val $prop: String = ${str(raw)}\n")
        }
        sb.append("}\n")
        return file(pkg, listOf("androidx.compose.runtime.Immutable"), sb.toString())
    }

    private fun shadowsFile(pkg: String, themes: List<String>, tokens: List<Map<String, Any?>>): String {
        val sb = StringBuilder("""
            |@Immutable
            |public data class SeaGlassShadowLayer(
            |    public val offsetX: Dp,
            |    public val offsetY: Dp,
            |    public val blur: Dp,
            |    public val spread: Dp,
            |    public val color: Color,
            |    public val inset: Boolean,
            |)
            |
            |@Immutable
            |public data class SeaGlassThemedShadow(
            |
        """.trimMargin())
        themes.forEach { sb.append("    public val ${ident(camel(it))}: List<SeaGlassShadowLayer>,\n") }
        sb.append(")\n\npublic object SeaGlassShadowTokens {\n")
        propertyNames(tokens.map { it["name"].toString() }).forEach { (name, prop) ->
            val value = tokens.first { it["name"].toString() == name }["value"]
            sb.append("    public val $prop: SeaGlassThemedShadow = SeaGlassThemedShadow(\n")
            themes.forEach { th ->
                sb.append("        ${ident(camel(th))} = listOf(\n")
                shadowLayers(pick(value, th, themes.first())).forEach { l -> sb.append("            $l,\n") }
                sb.append("        ),\n")
            }
            sb.append("    )\n")
        }
        sb.append("}\n")
        return file(pkg, listOf("androidx.compose.runtime.Immutable", "androidx.compose.ui.graphics.Color", "androidx.compose.ui.unit.Dp", "androidx.compose.ui.unit.dp"), sb.toString())
    }

    private fun infoFile(pkg: String, root: Map<String, Any?>, source: String): String {
        val sha = MessageDigest.getInstance("SHA-256").digest(source.toByteArray()).joinToString("") { "%02x".format(it) }
        val version = (root["version"] as? Number)?.toInt() ?: 0
        return file(pkg, emptyList(), """
            |public object SeaGlassTokenInfo {
            |    public const val NAME: String = ${str(root["name"]?.toString() ?: "")}
            |    public const val VERSION: Int = $version
            |    public const val SOURCE_SHA256: String = "$sha"
            |}
            |
        """.trimMargin())
    }

    private fun file(pkg: String, imports: List<String>, body: String): String {
        val head = "$MARKER from the Sea Glass tokens.json. Do not edit by hand.\npackage $pkg\n\n"
        val imp = if (imports.isEmpty()) "" else imports.sorted().joinToString("\n") { "import $it" } + "\n\n"
        return head + imp + body
    }

    @Suppress("UNCHECKED_CAST")
    private fun obj(v: Any?): Map<String, Any?> = v as? Map<String, Any?> ?: emptyMap()

    @Suppress("UNCHECKED_CAST")
    private fun list(v: Any?): List<Any?> = v as? List<Any?> ?: emptyList()

    private fun pick(v: Any?, theme: String, first: String): String = when (v) {
        is Map<*, *> -> (v[theme] ?: v[first] ?: v.values.first { it != null }).toString()
        else -> v.toString()
    }

    private fun key(name: String) = name.lowercase().replace("-", "").replace("_", "")

    private fun words(name: String) = name.split('-', '_', '.', ' ').filter { it.isNotEmpty() }

    private fun camel(name: String): String = words(name).mapIndexed { i, w ->
        if (i == 0) w.replaceFirstChar { it.lowercaseChar() } else w.replaceFirstChar { it.uppercaseChar() }
    }.joinToString("")

    private fun pascal(name: String): String = words(name).joinToString("") { w ->
        if (w.length <= 2 && w.all { it.isLetter() }) w.uppercase() else w.replaceFirstChar { it.uppercaseChar() }
    }

    private fun ident(name: String) = if (name in KEYWORDS) "`$name`" else name

    private fun paletteName(k: String) = PALETTE_NAMES[k] ?: pascal(k)

    // Strips a prefix shared by every token in a family (radius-, blur-, shape-) unless that would collide or start with a digit.
    private fun propertyNames(names: List<String>): List<Pair<String, String>> {
        val prefix = names.map { words(it).first() }.toSet().singleOrNull()?.takeIf { names.size > 1 && names.all { n -> words(n).size > 1 } }
        val stripped = names.map { n -> if (prefix != null) pascal(words(n).drop(1).joinToString("-")) else pascal(n) }
        val ok = prefix != null && stripped.toSet().size == names.size && stripped.none { it.first().isDigit() }
        return names.mapIndexed { i, n -> n to (if (ok) stripped[i] else pascal(n)).let { if (it.first().isDigit()) "T$it" else it } }
    }

    private fun num(d: Double): String = if (d == Math.floor(d) && !d.isInfinite() && kotlin.math.abs(d) < 1e9) d.toLong().toString() else d.toString()

    private fun float(v: Any?): String = when (v) {
        null -> "Float.NaN"
        is Number -> num(v.toDouble()).let { if ('.' in it) "${it}f" else "$it.0f" }
        else -> float(v.toString().toDouble())
    }

    private fun str(s: String) = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""

    private fun signed(n: String, unit: String) = if (n.startsWith("-")) "($n).$unit" else "$n.$unit"

    private fun weight(v: Any): String = when (v) {
        is Number -> v.toInt().toString()
        else -> when (val s = v.toString().trim()) { "normal" -> "400"; "bold" -> "700"; else -> s.split(' ').first() }
    }

    private fun textUnit(v: Any): String {
        if (v is Number) return signed(num(v.toDouble()), if (v.toDouble() < 10) "em" else "sp")
        val m = LENGTH.matchEntire(v.toString().trim()) ?: error("Unsupported text length '$v'")
        val n = m.groupValues[1].toDouble()
        return when (m.groupValues[2]) {
            "px", "" -> if (m.groupValues[2].isEmpty() && n < 10) signed(num(n), "em") else signed(num(n), "sp")
            "rem" -> signed(num(n * 16), "sp")
            "em" -> signed(num(n), "em")
            else -> error("Unsupported text length '$v'")
        }
    }

    private fun dimen(v: Any?): Pair<String, String> {
        if (v is Number) return "Float" to float(v)
        val s = v.toString().trim()
        val m = LENGTH.matchEntire(s) ?: return "String" to str(s)
        val n = m.groupValues[1].toDouble()
        return when (m.groupValues[2]) {
            "px" -> "Dp" to signed(num(n), "dp")
            "rem" -> "Dp" to signed(num(n * 16), "dp")
            "%" -> "Float" to float(n / 100)
            "" -> "Float" to float(n)
            else -> "String" to str(s)
        }
    }

    // CSS border-radius shorthand of percentages -> fractions (top-left, top-right, bottom-right, bottom-left; x then y).
    private fun corners(v: String): List<Double>? {
        val sides = v.split('/').map { side -> side.trim().split(Regex("\\s+")).map { it.removeSuffix("%").toDoubleOrNull()?.div(100) ?: return null } }
        fun expand(p: List<Double>) = when (p.size) {
            1 -> listOf(p[0], p[0], p[0], p[0])
            2 -> listOf(p[0], p[1], p[0], p[1])
            3 -> listOf(p[0], p[1], p[2], p[1])
            4 -> p
            else -> null
        }
        if (v.split('/').flatMap { it.trim().split(Regex("\\s+")) }.any { !it.endsWith("%") }) return null
        val x = expand(sides[0]) ?: return null
        val y = if (sides.size > 1) expand(sides[1]) ?: return null else x
        return x + y
    }

    // Splits a CSS box-shadow list into Kotlin SeaGlassShadowLayer constructor calls.
    private fun shadowLayers(css: String): List<String> {
        if (css.trim() == "none") return emptyList()
        val layers = mutableListOf<String>()
        var depth = 0
        var start = 0
        css.forEachIndexed { i, c ->
            if (c == '(') depth++ else if (c == ')') depth-- else if (c == ',' && depth == 0) { layers += css.substring(start, i); start = i + 1 }
        }
        layers += css.substring(start)
        return layers.map { layer ->
            val parts = Regex("""[a-z]+\([^)]*\)|#[0-9a-fA-F]+|[^\s]+""").findAll(layer.trim()).map { it.value }.toList()
            val inset = "inset" in parts
            val color = parts.firstOrNull { it.startsWith("#") || it.startsWith("rgb") || it.startsWith("hsl") } ?: "#000000"
            val lengths = parts.filter { it != "inset" && it != color }.map { LENGTH.matchEntire(it)?.groupValues?.get(1)?.toDouble() ?: error("Unsupported shadow part '$it'") }
            val l = lengths + List((4 - lengths.size).coerceAtLeast(0)) { 0.0 }
            "SeaGlassShadowLayer(${signed(num(l[0]), "dp")}, ${signed(num(l[1]), "dp")}, ${signed(num(l[2]), "dp")}, ${signed(num(l[3]), "dp")}, ${kColor(argb(color))}, inset = $inset)"
        }
    }

    private fun kColor(argb: Long) = "Color(0x%08X)".format(argb)

    private fun argb(css: String): Long {
        val s = css.trim().lowercase()
        if (s.startsWith("#")) {
            val h = s.substring(1)
            val full = when (h.length) {
                3 -> h.map { "$it$it" }.joinToString("") + "ff"
                4 -> h.map { "$it$it" }.joinToString("")
                6 -> h + "ff"
                8 -> h
                else -> error("Unsupported colour '$css'")
            }
            return (full.substring(6, 8).toLong(16) shl 24) or full.substring(0, 6).toLong(16)
        }
        val m = Regex("""rgba?\(([^)]*)\)""").matchEntire(s) ?: error("Unsupported colour '$css' (use hex or rgb/rgba)")
        val parts = m.groupValues[1].split(',', ' ', '/').filter { it.isNotBlank() }
        val (r, g, b) = parts.take(3).map { it.trim().toDouble().roundToInt().toLong() }
        val a = parts.getOrNull(3)?.trim()?.let { p -> if (p.endsWith("%")) p.dropLast(1).toDouble() / 100 else p.toDouble() } ?: 1.0
        return ((a * 255).roundToInt().toLong() shl 24) or (r shl 16) or (g shl 8) or b
    }
}

